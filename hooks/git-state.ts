import type { ClotureKind, ClotureTone, ClotureVerdict } from '../types'

export type Run = (
  argv: readonly string[],
) => Promise<{ exitCode: number; stdout: string; stderr: string }>

// Porcelain v1 -z : "XY path\0", a rename or copy adds one "origin\0" entry.
export function countEntries(stdout: string): number {
  const tokens = stdout.split('\0').filter(t => t.length > 0)
  let count = 0
  for (let i = 0; i < tokens.length; i++) {
    count += 1
    const code = tokens[i]?.[0]
    if (code === 'R' || code === 'C') i += 1
  }
  return count
}

export async function computeVerdict(run: Run): Promise<ClotureVerdict> {
  const empty = { dirty: 0, ahead: 0, stash: 0, branch: '', worktrees: 0 }
  try {
    const inside = await run(['git', 'rev-parse', '--is-inside-work-tree'])
    if (inside.exitCode !== 0) return { kind: 'HORS_GIT', ...empty }

    const [status, branchOut, stashOut, upstream] = await Promise.all([
      run(['git', 'status', '--porcelain=v1', '-z', '--untracked-files=normal']),
      run(['git', 'rev-parse', '--abbrev-ref', 'HEAD']),
      run(['git', 'stash', 'list']),
      run(['git', 'rev-parse', '--abbrev-ref', '@{u}']),
    ])
    if (status.exitCode !== 0) return { kind: 'ERREUR', ...empty }
    const dirty = countEntries(status.stdout)
    const branch = branchOut.stdout.trim()
    const stash = stashOut.stdout.split('\n').filter(Boolean).length

    let ahead = 0
    const hasUpstream = upstream.exitCode === 0
    if (hasUpstream) {
      const counts = await run(['git', 'rev-list', '--left-right', '--count', '@{u}...HEAD'])
      const parts = counts.stdout.trim().split(/\s+/)
      ahead = counts.exitCode === 0 ? Number(parts[1]) || 0 : 0
    }

    const base = { dirty, ahead, stash, branch, worktrees: 0 }
    if (dirty > 0) return { kind: 'NON_COMMITE', ...base }
    if (!hasUpstream) return { kind: 'SANS_REMOTE', ...base }
    if (ahead > 0) return { kind: 'NON_POUSSE', ...base }
    return { kind: 'PROPRE', ...base }
  } catch {
    return { kind: 'ERREUR', ...empty }
  }
}

const KINDS: readonly ClotureKind[] = ['PROPRE', 'NON_COMMITE', 'NON_POUSSE', 'SANS_REMOTE', 'HORS_GIT', 'ERREUR']

// Output of `cloture_check.py --git-only DIR` (the optional source of truth).
export function parseChecker(stdout: string): ClotureVerdict | null {
  try {
    const o = JSON.parse(stdout)
    if (!KINDS.includes(o.kind)) return null
    return {
      kind: o.kind,
      dirty: Number(o.dirty) || 0,
      ahead: Number(o.ahead) || 0,
      stash: Number(o.stash) || 0,
      branch: typeof o.branch === 'string' ? o.branch : '',
      worktrees: Number(o.worktrees) || 0,
      generated: Number(o.generated) || 0,
      foreign: Number(o.foreign) || 0,
    }
  } catch {
    return null
  }
}

export function tone(v: ClotureVerdict): ClotureTone {
  if (v.kind === 'PROPRE') return 'ok'
  if (v.kind === 'HORS_GIT') return 'warn'
  return 'stop'
}

export function headline(v: ClotureVerdict): string {
  const t = tone(v)
  if (t === 'ok') return 'Oui, tu peux fermer'
  if (t === 'warn') return 'Oui, côté git'
  return 'Non, pas encore'
}

// Counts the checker left out of the verdict: files regenerated by a declared producer, and changes
// that pre-date this session (baseline taken at session start). Shown, never blocking.
export function extras(v: ClotureVerdict): string {
  const bits: string[] = []
  if ((v.generated ?? 0) > 0) bits.push(`${v.generated} régénéré(s)`)
  if ((v.foreign ?? 0) > 0) bits.push(`${v.foreign} hors session`)
  return bits.length ? `(+ ${bits.join(', ')}, non bloquant)` : ''
}

export function reason(v: ClotureVerdict): string {
  const facts: string[] = []
  if (v.dirty > 0) facts.push(`${v.dirty} non commité(s)`)
  if (v.worktrees > 0) facts.push(`${v.worktrees} worktree(s) sale(s)`)
  if (v.ahead > 0) facts.push(`${v.ahead} non poussé(s)`)
  if (v.kind === 'SANS_REMOTE') facts.push('aucun remote ou amont : rien de sauvegardé en ligne')
  if (v.stash > 0) facts.push(`${v.stash} stash à vérifier`)
  switch (v.kind) {
    case 'PROPRE':
      return (v.stash > 0 ? facts.join(', ') : 'dépôt propre et poussé') + (extras(v) ? ` ${extras(v)}` : '')
    case 'HORS_GIT':
      return 'dossier hors dépôt git : rien à pousser, vérifie tes fichiers toi-même'
    case 'ERREUR':
      return 'état git illisible'
    default:
      return facts.join(', ')
  }
}

export function describe(v: ClotureVerdict): string {
  return `${headline(v)} : ${reason(v)}`
}

export const TICK_MS = 5_000
export const POLL_MS = 30_000
export const WAIT_POLL_MS = 5_000
export const WAIT_MAX_MS = 10 * 60_000
export const MAX_AGE_MS = 120_000

// A tick (every POLL_MS) recomputes while the verdict is not green, so a commit or push made
// outside the session shows up; once green it only keeps a slow refresh. A write tool forces it.
export function shouldRefresh(kind: ClotureKind | null, ageMs: number, isDirty: boolean, isWaiting = false): boolean {
  if (isDirty || kind === null) return true
  if (kind === 'PROPRE' || kind === 'HORS_GIT') return ageMs > MAX_AGE_MS
  if (isWaiting) return ageMs >= WAIT_POLL_MS
  return ageMs >= POLL_MS
}

// Forward slashes only: in a template literal a lone backslash would swallow the next character.
export function checkerScript(home: string): string {
  return `${home.replace(/\\/g, '/')}/.claude/scripts/cloture_check.py`
}
